/**
 * Writes supabase/seed.sql from the sample data in @dyh/core, so a fresh
 * Supabase project starts with the same clinics, doctors, staff and demo
 * patients the mock adapter uses.
 *
 *   pnpm seed:gen
 *
 * Staff rows are created without a Firebase uid. Run
 * `npm run link-staff` in firebase/functions afterwards to create their
 * Firebase logins (see docs/BACKEND.md).
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ADMINS, ANNOUNCEMENTS, DEFAULT_SETTINGS, DOCTOR_PATIENTS, DOCTORS, FAMILY, GENERATED_REPORTS, ME, MY_BOOKINGS, MY_RECORDS,
  PASSWORD_REQUESTS, ROOMS, SECRETARIES, SPECIALIZATIONS,
} from '../packages/core/src';

type V = string | number | boolean | null | undefined | object;

const lit = (v: V): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (typeof v === 'object') return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${v.replace(/'/g, "''")}'`;
};
const arr = (xs: (string | number)[]) => (xs.length ? `array[${xs.map((x) => lit(x)).join(', ')}]` : `'{}'`);
const row = (xs: V[]) => `  (${xs.map(lit).join(', ')})`;
const rowRaw = (xs: string[]) => `  (${xs.join(', ')})`;
const insert = (table: string, cols: string[], rows: string[], conflict = 'on conflict do nothing') =>
  rows.length ? `insert into ${table} (${cols.join(', ')}) values\n${rows.join(',\n')}\n${conflict};\n` : '';

const out: string[] = [];
out.push(`-- Generated by scripts/gen-seed.ts from @dyh/core sample data. Do not edit by hand.
-- Demo data only: replace with real records before going live.
`);

out.push(`-- Your Firebase project id (Project settings → General). Tokens from any other project are rejected.
insert into app.config (key, value) values ('firebase_project_id', 'YOUR-FIREBASE-PROJECT-ID') on conflict (key) do nothing;
`);

out.push(insert('public.system_settings', ['id', 'data'], [row([true, DEFAULT_SETTINGS])], 'on conflict (id) do nothing'));

const CLINIC_SERVICES = ['Konsultasyon', 'Balik-konsulta', 'Medical certificate'];
out.push(insert('public.specializations', ['id', 'name_tl', 'name_en', 'icon', 'services', 'clinic_services', 'sort'],
  SPECIALIZATIONS.map((s, i) => rowRaw([lit(s.id), lit(s.name.tl), lit(s.name.en), lit(s.icon), arr(s.services), arr([...CLINIC_SERVICES, ...s.services]), String(i)]))));

out.push(insert('public.rooms', ['number', 'floor', 'capacity'], ROOMS.map((r) => row([r.number, r.floor, r.capacity]))));

out.push(insert('public.doctors',
  ['id', 'name', 'specialization_id', 'room', 'floor', 'clinic_days', 'hours_start', 'hours_end', 'queue_prefix', 'credentials', 'email', 'mobile', 'max_patients_per_day', 'status'],
  DOCTORS.map((d) => rowRaw([lit(d.id), lit(d.name), lit(d.specializationId), lit(d.room), lit(d.floor), arr(d.clinicDays), lit(d.hours.start), lit(d.hours.end),
    lit(d.queuePrefix), arr(d.credentials), lit(d.email), lit(d.mobile), lit(d.maxPatientsPerDay), lit(d.status)]))));

out.push(insert('public.secretaries', ['id', 'name', 'email', 'mobile', 'status', 'created_at', 'created_by'],
  SECRETARIES.map((s) => row([s.id, s.name, s.email, s.mobile, s.status, s.createdAt, s.createdBy]))));
out.push(insert('public.secretary_doctors', ['secretary_id', 'doctor_id'], SECRETARIES.flatMap((s) => s.doctorIds.map((d) => row([s.id, d])))));

out.push(insert('public.admins', ['id', 'name', 'email', 'mobile', 'role', 'permissions', 'doctor_id', 'credentials', 'status', 'created_at', 'created_by'],
  ADMINS.map((a) => rowRaw([lit(a.id), lit(a.name), lit(a.email), lit(a.mobile), lit(a.role), lit(a.permissions), lit(a.doctorId), arr(a.credentials ?? []), lit(a.status), lit(a.createdAt), lit(a.createdBy)]))));

out.push(insert('public.announcements', ['id', 'icon', 'colors', 'title', 'subtitle', 'summary', 'body', 'from_date', 'to_date', 'audience', 'is_draft'],
  ANNOUNCEMENTS.map((a) => rowRaw([lit(a.id), lit(a.icon), arr(a.colors), lit(a.title), lit(a.subtitle), lit(a.summary), lit(a.body), lit(a.from), lit(a.to), `${lit(JSON.stringify(a.audience))}::jsonb`, lit(a.status === 'draft')]))));

/* Demo patients: the Patient App's account holder, their family, and Dr. Santos's patients. */
const patients = new Map<string, { id: string; last: string; first: string; middle?: string; display: string; birthday: string | null; age?: number; sex: string | null; mobile: string; city?: string; blood: string; allergies: string[]; priority: string | null; ec?: object; via: string }>();
const addP = (p: (typeof DOCTOR_PATIENTS)[number], via = 'import') =>
  patients.set(p.id, { id: p.id, last: p.name.last, first: p.name.first, middle: p.name.middle, display: p.displayName, birthday: p.birthday, sex: p.sex, mobile: p.mobile, city: p.city, blood: p.bloodType, allergies: p.allergies, priority: p.priority, ec: p.emergencyContact, via });
addP(ME);
DOCTOR_PATIENTS.forEach((p) => !patients.has(p.id) && addP(p));
patients.set('DYH-2026-005120', { id: 'DYH-2026-005120', last: 'Dela Cruz', first: 'Sofia', display: 'Sofia Dela Cruz', birthday: '2019-08-11', sex: 'F', mobile: ME.mobile, city: ME.city, blood: 'A+', allergies: [], priority: null, via: 'import' });
for (const f of FAMILY) {
  if (patients.has(f.patientId)) continue;
  const [first, ...rest] = f.displayName.split(' ');
  patients.set(f.patientId, { id: f.patientId, last: rest.join(' '), first, display: f.displayName, birthday: null, age: f.age, sex: null, mobile: ME.mobile, blood: 'unknown', allergies: [], priority: f.priority, via: 'family' });
}
out.push(insert('public.patients',
  ['id', 'last_name', 'first_name', 'middle_name', 'display_name', 'birthday', 'approx_age', 'sex', 'mobile', 'city', 'blood_type', 'allergies', 'priority', 'emergency_contact', 'created_via'],
  [...patients.values()].map((p) => rowRaw([lit(p.id), lit(p.last), lit(p.first), lit(p.middle), lit(p.display), lit(p.birthday), lit(p.age), lit(p.sex), lit(p.mobile), lit(p.city), lit(p.blood), arr(p.allergies), lit(p.priority), lit(p.ec), lit(p.via)]))));

out.push(insert('public.family_links', ['owner_patient_id', 'member_patient_id', 'relation'], FAMILY.map((f) => row([ME.id, f.patientId, f.relation]))));

out.push(insert('public.bookings', ['id', 'patient_id', 'doctor_id', 'date', 'type', 'status', 'queue_number', 'is_follow_up'],
  MY_BOOKINGS.map((b) => row([b.id, b.patientId, b.doctorId, b.date, b.type, b.status, b.queueNumber, !!b.isFollowUp]))));

/* Past signed records for the demo patient (hash-chained like real ones). */
out.push(`-- Demo medical records. Consultations are append-only; the hash chain starts here.
do $$
declare v_prev text; v_body jsonb;
begin
${[...MY_RECORDS].reverse().map((r) => `  v_body := ${lit({ ...r, addendum: undefined, integrityHash: undefined })};
  insert into public.consultations (id, patient_id, doctor_id, date, type, title, diagnoses, findings, prescriptions, labs, notes, vitals, verified_with, source, signed_at, prev_hash, integrity_hash)
  values (${lit(r.id)}, ${lit(r.patientId)}, ${lit(r.doctorId)}, ${lit(r.date)}, ${lit(r.type)}, ${lit(r.title ?? null)}, ${lit(r.diagnoses)}, ${lit(r.findings)}, ${lit(r.prescriptions)},
          ${arr(r.labs)}, ${lit(r.notes)}, ${lit(r.vitals ?? null)}, 'pin', 'typed', ${lit(r.date)}::date + time '11:00', v_prev,
          encode(extensions.digest(coalesce(v_prev, '') || v_body::text, 'sha256'), 'hex'))
  on conflict do nothing
  returning integrity_hash into v_prev;${r.addendum ? `
  insert into public.addenda (consultation_id, author_doctor_id, text, created_at) values (${lit(r.id)}, ${lit(r.addendum.authorDoctorId)}, ${lit(r.addendum.text.en)}, ${lit(r.addendum.date)});` : ''}`).join('\n')}
end $$;
`);

out.push(insert('public.generated_reports', ['id', 'scope', 'title', 'from_date', 'to_date', 'generated_on'],
  GENERATED_REPORTS.map((r) => row([r.id, r.scope, r.title, r.from, r.to, r.generatedOn]))));

out.push(insert('public.password_requests', ['id', 'name', 'role', 'email', 'message', 'otp_verified', 'status', 'created_at'],
  PASSWORD_REQUESTS.map((r) => rowRaw([lit(r.id), lit(r.name), lit(r.role), lit(r.email), lit(r.message), lit(r.otpVerified), lit(r.status),
    `(${lit(r.requestedOn)}::date + ${lit(r.time)}::time) at time zone 'Asia/Manila'`]))));

out.push(`-- Demo kiosk. Device key: demo-kiosk-key  (create real ones with a long random key; see docs/BACKEND.md)
insert into public.kiosk_devices (id, name, key_hash) values ('kiosk-1', 'OPD Lobby Kiosk', encode(extensions.digest('demo-kiosk-key', 'sha256'), 'hex')) on conflict do nothing;

-- Start new patient ids after the demo ones.
select setval('public.patient_seq', 5300);

`);

const file = resolve(dirname(fileURLToPath(import.meta.url)), '../supabase/seed.sql');
writeFileSync(file, out.join('\n'));
console.log(`Wrote ${file}`);
